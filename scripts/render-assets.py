"""Render the generated wallpaper, lock-screen art and preview for each Noir theme.

A theme's `backgrounds/0-*` photograph, when present, is used as the preview backdrop.

Needs ImageMagick (`magick`). Outputs are committed, not regenerated by
`generate-themes.py --check`, because encoders are not byte-stable.
"""
from pathlib import Path
import subprocess
import tomllib

ROOT = Path(__file__).resolve().parents[1]
THEMES = tomllib.loads((ROOT / "themes/palettes.toml").read_text())["themes"]


def mix(a, b, pct):
    return "#" + "".join(f"{(int(a[i:i+2], 16) * (100 - pct) + int(b[i:i+2], 16) * pct + 50) // 100:02x}" for i in (1, 3, 5))


def magick(*args):
    subprocess.run(["magick", *map(str, args)], check=True)


for theme in THEMES:
    out = ROOT / "themes" / theme["slug"]
    bg, fg, accent = theme["bg"], theme["fg"], theme["ansi"][4]
    (out / "backgrounds").mkdir(exist_ok=True)
    a = theme["ansi"]
    percent = (38, 30, 26) if theme["is_dark"] else (34, 26, 22)
    glows = [(a[4], 1500, 760, 600, 1130, percent[0]), (a[5], 1300, 640, 1950, 480, percent[1]),
             (a[6], 1200, 560, 1550, 1240, percent[2])]
    wallpaper = out / "backgrounds/1-aurora.png"
    magick("-size", "2560x1440", f"xc:{bg}", "-depth", "16", wallpaper)
    for colour, width, height, x, y, strength in glows:
        # Soft-edged ellipse of palette colour, blended over the background through a blurred mask.
        magick(wallpaper, "(", "-size", "2560x1440", f"xc:{colour}", ")",
               "(", "-size", "2560x1440", "xc:black", "-fill", "white", "-draw",
               f"ellipse {x},{y} {width // 2},{height // 2} 0,360", "-blur", "0x240", "-alpha", "off", "-colorspace", "Gray",
               "-evaluate", "multiply", f"{strength / 100:.2f}", ")", "-composite", wallpaper)
    # Light grain so 8-bit output does not band.
    magick(wallpaper, "(", "-size", "2560x1440", "xc:gray50", "+noise", "Gaussian", "-attenuate", "0.06",
           "-colorspace", "gray", ")", "-compose", "overlay", "-composite", "-depth", "8", "-strip",
           "-define", "png:color-type=2", wallpaper)
    # Lock-screen mark: an original `>_` prompt in the theme accent, with a glow.
    mark = ["-stroke", accent, "-strokewidth", "34", "-fill", "none", "-draw", "stroke-linecap round stroke-linejoin round polyline 150,110 330,250 150,390",
            "-draw", "stroke-linecap round line 430,410 640,410"]
    magick("-size", "800x520", "xc:none", *mark, "(", "+clone", "-blur", "0x26", ")", "(", "+clone", "-blur", "0x10", ")",
           "-reverse", "-background", "none", "-compose", "over", "-layers", "flatten", "-strip", out / "unlock.png")
    magick("-size", "1920x1080", f"xc:{bg}", out / "unlock.png", "-gravity", "center", "-composite", "-strip",
           "-define", "png:color-type=2", out / "preview-unlock.png")

    prompt = [f"{a[2]}|~/src $ ls", f"{a[4]}|notes.md  src/  themes/", f"{fg}|$ git status", f"{a[3]}|M README.md",
              f"{a[1]}|D old.txt", f"{a[5]}|? new.txt"]
    window = ["-size", "1480x760", f"xc:{bg}", "-gravity", "NorthWest", "-fill", mix(bg, fg, 8), "-draw", "rectangle 0,0 1480,56",
              "-fill", a[1], "-draw", "circle 36,28 36,40", "-fill", a[3], "-draw", "circle 76,28 76,40",
              "-fill", a[2], "-draw", "circle 116,28 116,40", "-font", "JetBrains-Mono-Regular", "-pointsize", "34"]
    for row, line in enumerate(prompt):
        colour, text = line.split("|", 1)
        window += ["-fill", colour, "-annotate", f"+48+{130 + row * 58}", text]
    for i, colour in enumerate(a):
        window += ["-fill", colour, "-draw", f"rectangle {48 + i * 86},{560 + (i // 8) * 70} {118 + i * 86 if False else 48 + (i % 8) * 86 + 70},{620 + (i // 8) * 70}"] if False else []
    for i, colour in enumerate(a):
        x, y = 48 + (i % 8) * 86, 520 + (i // 8) * 80
        window += ["-fill", colour, "-draw", f"roundrectangle {x},{y} {x + 70},{y + 64} 10,10"]
    bar = ["-size", "2560x56", f"xc:{mix(bg, fg, 5)}", "-gravity", "NorthWest", "-fill", a[4], "-draw", "circle 40,28 40,36",
           "-fill", fg, "-font", "JetBrains-Mono-Regular", "-pointsize", "26", "-annotate", "+1130+12", "Sunday 16:21"]
    base = sorted((out / "backgrounds").glob("0-*"))[:1] or [wallpaper]
    magick(base[0], "-resize", "2560x1440^", "-gravity", "center", "-extent", "2560x1440", "(", *window, "(", "+clone", "-background", "black", "-shadow", "60x30+0+20", ")", "+swap",
           "-background", "none", "-layers", "merge", "+repage", ")", "-gravity", "center", "-geometry", "+0+30",
           "-composite", "(", *bar, ")", "-gravity", "north", "-composite", "-strip", out / "preview.png")
