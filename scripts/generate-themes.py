"""Generate original Noir theme ports from the two canonical palettes.

Only ANSI, foreground, background and cursor are upstream palette values.
Desktop surfaces blend background toward foreground by 3/6/12 percent;
selection blends background toward ANSI blue by 22 percent. These semantic
roles are derived here, never substituted for the original terminal palette.
"""
import argparse
import hashlib
from pathlib import Path
import re
import struct
import subprocess
import tomllib
import zlib

ROOT = Path(__file__).resolve().parents[1]
PALETTES = ROOT / "themes/palettes.toml"
NAMES = {"Noir": "noir", "Noir Clair": "noir-clair"}
HEADER = "# Copyright (C) 2026 Stanislav Yaglo\n# SPDX-License-Identifier: Apache-2.0\n# Generated by scripts/generate-themes.py; edit themes/palettes.toml.\n"


def mix(first, second, percent):
    return "#" + "".join(f"{(int(first[i:i + 2], 16) * (100 - percent) + int(second[i:i + 2], 16) * percent + 50) // 100:02x}" for i in (1, 3, 5))


def roles(theme):
    a, bg, fg = theme["ansi"], theme["bg"], theme["fg"]
    result = dict(mode="dark" if theme["is_dark"] else "light", accent=a[4],
                  background=bg, foreground=fg, cursor=theme["cursor"],
                  dark_background=mix(bg, fg, 6), darker_background=mix(bg, fg, 12),
                  lighter_background=mix(bg, fg, 3), dark_foreground=mix(fg, bg, 45),
                  light_foreground=fg, bright_foreground=a[15], muted=a[8],
                  selection=mix(bg, a[4], 22), selection_foreground=fg)
    result["selection_background"] = result["selection"]
    for index, name in enumerate(("red", "green", "yellow", "blue", "magenta", "cyan"), 1):
        result[name], result["bright_" + name] = a[index], a[index + 8]
    result.update(purple=a[5], bright_purple=a[13], orange=a[3], brown=mix(a[3], bg, 50))
    for canonical, alias in (("background", "bg"), ("foreground", "fg"), ("dark_background", "dark_bg"),
                             ("darker_background", "darker_bg"), ("lighter_background", "lighter_bg"),
                             ("dark_foreground", "dark_fg"), ("light_foreground", "light_fg"), ("bright_foreground", "bright_fg")):
        result[alias] = result[canonical]
    result.update({f"color{i}": color for i, color in enumerate(a)})
    return result


def solid_png(color):
    """Original 64×64 RGB background, without image-library dependencies."""
    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))
    pixel = bytes.fromhex(color[1:])
    data = b"\x00" + pixel * 64
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", 64, 64, 8, 2, 0, 0, 0)) + chunk(b"IDAT", zlib.compress(data * 64, 9)) + chunk(b"IEND", b"")


def outputs(theme):
    a, semantic = theme["ansi"], roles(theme)
    colors = HEADER + "\n" + "".join(f'{name} = "{value}"\n' for name, value in semantic.items())
    foot = HEADER
    # Omarchy includes the colors-dark section even for a light desktop theme.
    # Also provide colors-light so Foot's own color-mode switch preserves it.
    for section in ("colors-dark", "colors-light"):
        foot += f"\n[{section}]\nforeground={theme['fg'][1:]}\nbackground={theme['bg'][1:]}\n"
        foot += f"cursor={theme['bg'][1:]} {theme['cursor'][1:]}\nselection-foreground={semantic['selection_foreground'][1:]}\nselection-background={semantic['selection'][1:]}\n"
        foot += "".join(f"{'regular' if i < 8 else 'bright'}{i % 8}={color[1:]}\n" for i, color in enumerate(a))
    kitty = HEADER + f"foreground {theme['fg']}\nbackground {theme['bg']}\ncursor {theme['cursor']}\ncursor_text_color {theme['bg']}\nselection_foreground {semantic['selection_foreground']}\nselection_background {semantic['selection']}\n" + "".join(f"color{i} {color}\n" for i, color in enumerate(a))
    ghostty = HEADER + f"foreground = {theme['fg'][1:]}\nbackground = {theme['bg'][1:]}\ncursor-color = {theme['cursor'][1:]}\ncursor-text = {theme['bg'][1:]}\nselection-foreground = {semantic['selection_foreground'][1:]}\nselection-background = {semantic['selection'][1:]}\n" + "".join(f"palette = {i}={color[1:]}\n" for i, color in enumerate(a))
    alacritty = HEADER + f'\n[colors.primary]\nforeground = "{theme["fg"]}"\nbackground = "{theme["bg"]}"\n\n[colors.cursor]\ncursor = "{theme["cursor"]}"\ntext = "{theme["bg"]}"\n\n[colors.selection]\ntext = "{semantic["selection_foreground"]}"\nbackground = "{semantic["selection"]}"\n'
    names = ("black", "red", "green", "yellow", "blue", "magenta", "cyan", "white")
    for section, values in (("normal", a[:8]), ("bright", a[8:])):
        alacritty += f"\n[colors.{section}]\n" + "".join(f'{key} = "{value}"\n' for key, value in zip(names, values))
    return {"colors.toml": colors.encode(), "foot.ini": foot.encode(), "kitty.conf": kitty.encode(),
            "ghostty.conf": ghostty.encode(), "alacritty.toml": alacritty.encode(),
            "backgrounds/solid.png": solid_png(theme["bg"])}


def import_core(source):
    source = source.resolve()
    upstream = tomllib.loads(source.read_text())
    selected = {theme["name"]: theme for theme in upstream["themes"] if theme["name"] in NAMES}
    if selected.keys() != NAMES.keys():
        raise ValueError("upstream must contain exactly Noir and Noir Clair")
    revision = subprocess.check_output(["git", "-C", str(source.parent), "rev-parse", "HEAD"], text=True).strip()
    text = "# Copyright (C) 2026 Stanislav Yaglo\n# SPDX-License-Identifier: Apache-2.0\n# Only Ubiquitty's two original house palettes; no adapted third-party schemes.\n"
    text += f'\nupstream_repository = "ubiquitty-core"\nupstream_path = "Source/Core/Themes/builtin-themes.toml"\nupstream_commit = "{revision}"\nupstream_file_sha256 = "{hashlib.sha256(source.read_bytes()).hexdigest()}"\n'
    for name in NAMES:
        theme = selected[name]
        text += f'\n[[themes]]\nname = "{name}"\nslug = "{NAMES[name]}"\nis_dark = {str(theme["is_dark"]).lower()}\n'
        text += "ansi = [" + ", ".join(f'"{color}"' for color in theme["ansi"]) + "]\n"
        text += "".join(f'{key} = "{theme[key]}"\n' for key in ("fg", "bg", "cursor"))
    PALETTES.write_text(text)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files differ")
    parser.add_argument("--import-core", type=Path, help="explicitly refresh only the two original palettes from Core TOML")
    args = parser.parse_args()
    if args.check and args.import_core:
        parser.error("--check and --import-core cannot be combined")
    if args.import_core:
        import_core(args.import_core)
    themes = tomllib.loads(PALETTES.read_text())["themes"]
    if len(themes) != 2 or {theme["name"] for theme in themes} != set(NAMES):
        raise ValueError("only Noir and Noir Clair may be generated")
    stale = []
    for theme in themes:
        if theme["slug"] != NAMES[theme["name"]] or len(theme["ansi"]) != 16:
            raise ValueError("invalid palette name or ANSI count")
        for color in theme["ansi"] + [theme[key] for key in ("fg", "bg", "cursor")]:
            if not re.fullmatch(r"#[0-9a-f]{6}", color):
                raise ValueError(f"invalid color {color}")
        for relative, content in outputs(theme).items():
            path = ROOT / "themes" / theme["slug"] / relative
            if args.check:
                if not path.exists() or path.read_bytes() != content:
                    stale.append(str(path.relative_to(ROOT)))
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(content)
    if stale:
        parser.exit(1, "Stale generated files: " + ", ".join(stale) + "\n")


if __name__ == "__main__":
    main()
